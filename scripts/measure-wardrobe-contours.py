"""Read PNG alpha contours for the clothing rig; never modify image pixels."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/generated/cat-items'
SHIRTS = ['red-shirt', 'green-shirt', 'blue-shirt', 'yellow-shirt', 'striped-shirt', 'heart-shirt', 'star-shirt', 'rainbow-shirt', 'orange-paw-shirt', 'teal-leaf-shirt', 'purple-moon-shirt', 'cream-flower-shirt']
BOTTOMS = ['pink-skirt', 'denim-skirt', 'rainbow-skirt', 'teal-dot-skirt', 'lavender-skirt', 'lemon-star-skirt', 'blue-pants', 'purple-pants', 'green-pants', 'yellow-shorts', 'red-shorts', 'denim-shorts']

def measure(item):
    path = next(p for p in [ART / f'{item}-v2.png', ART / f'{item}-v1.png'] if p.exists())
    with Image.open(path) as im:
        alpha = im.getchannel('A')
        l, t, r, b = alpha.point(lambda v: 255 if v >= 20 else 0).getbbox()
        w, h = r - l, b - t
        def spans(y):
            row = round(t + y * (h - 1))
            runs, start = [], None
            for x in range(l, r):
                present = alpha.getpixel((x, row)) >= 90
                if present and start is None: start = x
                if not present and start is not None:
                    if x - start > 3: runs.append(((start - l) / w, (x - l) / w))
                    start = None
            if start is not None: runs.append(((start - l) / w, 1))
            return runs
        if item in SHIRTS:
            rows = [0, .08, .18, .32, .5, .63, .78, 1]
            left, right = [.29, .26, .25, .235], [.71, .74, .75, .765]
            for y in [.5, .63, .78, .78]:
                center = next(run for run in spans(y) if run[0] < .5 < run[1])
                left.append(center[0]); right.append(center[1])
            return dict(rows=rows, left=left, right=right)
        if item.endswith('skirt'):
            rows = [0, .12, .28, .45, .65, .82, 1]
            samples = [.1, .12, .28, .45, .65, .65, .65]
            return dict(rows=rows, left=[spans(y)[0][0] for y in samples], right=[spans(y)[-1][1] for y in samples])
        crotch = next(i / 1000 for i in range(300, 900) if not any(a < .5 < z for a, z in spans(i / 1000)))
        rows = [0, .12, .3, crotch - .035, crotch + .045, (crotch + 1) / 2, .94, 1]
        left, right, inner_left, inner_right = [], [], [], []
        for y in rows:
            runs = spans(max(.06, min(.88, y)))
            left.append(runs[0][0]); right.append(runs[-1][1])
            inner_left.append(max((z for a, z in runs if z < .5), default=.5))
            inner_right.append(min((a for a, z in runs if a > .5), default=.5))
        return dict(rows=rows, left=left, right=right, innerLeft=inner_left, innerRight=inner_right)

data = {item: measure(item) for item in SHIRTS + BOTTOMS}
for entry in data.values():
    for key, values in entry.items(): entry[key] = [round(value, 5) for value in values]
output = ROOT / 'src/data/wardrobeContours.ts'
output.write_text('// Generated by scripts/measure-wardrobe-contours.py, read-only PNG alpha measurements.\n'
    'export type WardrobeContour = { rows: number[]; left: number[]; right: number[]; innerLeft?: number[]; innerRight?: number[] };\n'
    'export const wardrobeContours: Record<string, WardrobeContour> = {\n' + ',\n'.join('  ' + json.dumps(key) + ': ' + json.dumps(value, separators=(',', ':')) for key, value in data.items()) + '\n};\n')
print(f'Measured {len(data)} garments; PNG originals unchanged.')
