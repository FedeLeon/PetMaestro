const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright');
const { shopItems } = require('./load-game-data.cjs');
const catchYarn = require('./catch-yarn.cjs');
const output = process.env.REVIEW_OUTPUT || '/tmp/petmaestro-yarn';
const button = (page, name) => page.getByRole('button', { name, exact: true });
const saved = page => page.evaluate(() => JSON.parse(localStorage.getItem('petmaestro.progress.v1')));
async function run() {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
  const report = [];
  try {
    for (const viewport of [{ width: 1280, height: 720 }, { width: 844, height: 390 }]) {
      const page = await browser.newPage({ viewport, reducedMotion: 'no-preference' });
      page.setDefaultTimeout(15000);
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.addInitScript(() => {
        if (!localStorage.getItem('petmaestro.progress.v1')) localStorage.setItem('petmaestro.progress.v1', JSON.stringify({ coins: 7, ownedItems: ['yarn-ball', 'bell-ball'], needs: { play: 20 }, needsUpdatedAt: Date.now() }));
      });
      await page.goto(process.env.GAME_URL || 'http://localhost:8087');
      await button(page, 'Juguetes').waitFor({ timeout: 90000 });
      await button(page, 'Juguetes').click();
      await button(page, 'Jugar Ovillo').click();
      const target = button(page, 'Atrapar ovillo');
      await target.waitFor();
      const room = page.getByTestId('yarn-room');
      const bounds = await room.boundingBox();
      const counter = await page.getByTestId('yarn-counter').boundingBox();
      assert.ok(counter.x >= bounds.x && counter.y >= bounds.y && counter.x + counter.width <= bounds.x + bounds.width && counter.y + counter.height <= bounds.y + bounds.height, 'The framed counter stays inside the room');
      assert.equal(await page.getByTestId('yarn-counter').locator('img').count(), 2, 'Counter uses the themed frame asset and yarn icon');
      const frame = await page.getByTestId('yarn-counter').locator('img').first().boundingBox();
      assert.ok(Math.abs(frame.width - counter.width) < 1 && Math.abs(frame.height - counter.height) < 1, 'The actual frame asset fits the counter');
      const backdrop = await room.locator('img').first().boundingBox();
      assert.ok(Math.abs(backdrop.width - bounds.width) < 1 && Math.abs(backdrop.height - bounds.height) < 1, 'Room illustration fits without cropping');
      const boxStyle = await target.evaluate(el => ({ background: getComputedStyle(el).backgroundColor, border: getComputedStyle(el).borderWidth }));
      assert.equal(boxStyle.background, 'rgba(0, 0, 0, 0)', 'No frame background around the yarn');
      assert.ok(boxStyle.border === '0px' || boxStyle.border === '', 'No frame border around the yarn');
      await page.mouse.click(bounds.x + bounds.width * .5, bounds.y + bounds.height * .2);
      await page.getByLabel('0 de 6', { exact: true }).waitFor();
      assert.equal(await page.getByTestId('yarn-hit-sparkles').count(), 0, 'Floor taps never show success sparkles');
      const positions = [];
      const spins = new Set();
      for (let i = 0; i < 32; i++) {
        const rect = await target.boundingBox();
        assert.ok(rect.width >= 44 && rect.height >= 44);
        assert.ok(rect.x >= bounds.x && rect.x + rect.width <= bounds.x + bounds.width && rect.y >= bounds.y && rect.y + rect.height <= bounds.y + bounds.height, 'Moving touch area stays entirely within the room');
        assert.ok(rect.x >= counter.x + counter.width || rect.x + rect.width <= counter.x || rect.y >= counter.y + counter.height || rect.y + rect.height <= counter.y, 'Yarn never hides behind the framed counter');
        positions.push({ x: rect.x, y: rect.y });
        spins.add(await page.getByTestId('yarn-spin').evaluate(el => getComputedStyle(el).transform));
        if ([0, 12, 24].includes(i)) await page.screenshot({ path: `${output}/rolling-${viewport.width}-${i}.png` });
        await page.waitForTimeout(230);
      }
      assert.ok(spins.size > 8, 'Yarn rotates without waiting for a touch');
      assert.ok(Math.max(...positions.map(p => p.x)) - Math.min(...positions.map(p => p.x)) > bounds.width * .3, 'Yarn travels across the room automatically');
      assert.ok(Math.max(...positions.map(p => p.y)) - Math.min(...positions.map(p => p.y)) > 10, 'The route also changes depth on the floor');
      await page.getByLabel('0 de 6', { exact: true }).waitFor();
      const first = await target.boundingBox();
      await page.mouse.click(first.x + first.width / 2, first.y + first.height / 2, { clickCount: 2 });
      await page.getByLabel('1 de 6', { exact: true }).waitFor();
      assert.equal(await page.getByTestId('yarn-hit-sparkles').count(), 1, 'An accepted physical touch shows one sparkle burst, including on double taps');
      await page.waitForTimeout(130);
      await page.screenshot({ path: `${output}/hit-${viewport.width}.png` });
      await page.waitForTimeout(400);
      await catchYarn(page, 5);
      await page.getByLabel('6 de 6', { exact: true }).waitFor();
      assert.ok(await page.getByTestId('yarn-hit-sparkles').count() >= 1, 'The last hit celebrates before the result replaces the room');
      await page.getByText('¡Qué bien jugaron juntos!', { exact: true }).waitFor();
      assert.equal((await saved(page)).learning.toyBest['yarn-ball'], 6);
      assert.equal((await saved(page)).learning.counts.toy, 1);
      assert.equal((await saved(page)).coins, 12);
      assert.ok((await saved(page)).needs.play >= 44);
      await page.emulateMedia({ reducedMotion: 'reduce' });
      await button(page, 'Volver a jugar').click();
      await target.waitFor();
      await page.waitForTimeout(200);
      const still = await target.boundingBox();
      const stillSpin = await page.getByTestId('yarn-spin').evaluate(el => getComputedStyle(el).transform);
      await page.waitForTimeout(400);
      const after = await target.boundingBox();
      assert.ok(Math.abs(still.x - after.x) < 1 && Math.abs(still.y - after.y) < 1, 'Reduced motion pauses automatic travel');
      assert.equal(await page.getByTestId('yarn-spin').evaluate(el => getComputedStyle(el).transform), stillSpin, 'Reduced motion pauses spin');
      await catchYarn(page, 1);
      const next = await target.boundingBox();
      assert.ok(Math.abs(next.x - still.x) > 20, 'Reduced-motion play offers a new position after a touch');
      const hit = await page.getByTestId('yarn-hit-sparkles').boundingBox();
      assert.ok(Math.abs(hit.x + hit.width / 2 - still.x - still.width / 2) < 2, 'Sparkles stay at the caught position when the yarn moves to its next spot');
      await page.waitForTimeout(700);
      assert.equal(await page.getByTestId('yarn-hit-sparkles').count(), 0, 'Sparkles disappear after feedback');
      await catchYarn(page, 5);
      await page.getByText('¡Qué bien jugaron juntos!', { exact: true }).waitFor();
      assert.equal((await saved(page)).coins, 17, 'Each completed replay earns five coins');
      assert.equal((await saved(page)).learning.counts.toy, 2);
      await page.emulateMedia({ reducedMotion: 'no-preference' });
      await button(page, 'Volver a jugar').click();
      await catchYarn(page, 1);
      await button(page, 'Volver').click();
      await page.waitForTimeout(600);
      assert.equal((await saved(page)).learning.counts.toy, 2, 'Leaving does not finish a partial round');
      assert.equal(await page.getByTestId('yarn-motion').count(), 0);
      assert.equal(await page.getByTestId('yarn-hit-sparkles').count(), 0, 'Leaving removes all feedback');
      await button(page, 'Jugar Ovillo').click();
      await catchYarn(page, 6);
      await page.getByLabel('6 de 6', { exact: true }).waitFor();
      await button(page, 'Volver').click();
      await page.waitForTimeout(800);
      assert.equal((await saved(page)).learning.counts.toy, 2, 'Leaving during the final sparkle cancels the completion timer');
      assert.equal((await saved(page)).coins, 17, 'Canceled completion cannot issue a late reward');
      await button(page, `Jugar ${shopItems.find(i => i.id === 'bell-ball').name}`).click();
      await button(page, 'Empezar carrera').click();
      await page.getByText('¡Alcanzaste el cascabel!', { exact: true }).waitFor({ timeout: 25000 });
      assert.equal((await saved(page)).learning.toyBest['bell-ball'], 1, 'Bell runner completes after the short park chase');
      assert.deepEqual(errors, []);
      report.push({ viewport, positions, spinFrames: spins.size, errors });
      await page.close();
      console.log(`Rolling yarn: room, continuous travel/spin, boundaries, physical taps, double taps, rewards, reduced motion, exit and bell regression passed at ${viewport.width}×${viewport.height}.`);
    }
    fs.writeFileSync(`${output}/report.json`, JSON.stringify(report, null, 2));
  } finally { await browser.close(); }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
